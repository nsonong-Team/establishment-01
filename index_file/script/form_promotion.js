// ── Reset ──────────────────────────────────────────
function resetProForm() {
  const fields = [
    'pro-rep', 'pro-pos', 'pro-ag', 'pro-biz',
    'pro-หมวด1-อื่นๆ', 'pro-หมวด2-อื่นๆ', 'pro-หมวด3-อื่นๆ',
    'pro-หมวด4-อื่นๆ', 'pro-หมวด5-อื่นๆ', 'pro-note',
  ];
  fields.forEach(id => {
    const el = document.getElementById(id);
    if (el) el.value = '';
  });

  Object.keys(proCheckStates).forEach(id => {
    proCheckStates[id] = false;
    const el = document.getElementById('pro-item-' + id);
    if (el) el.classList.remove('checked');
  });
}