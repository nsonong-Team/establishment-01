const proCheckStates = {};

// ── Toggle checkbox ────────────────────────────────
function toggleProCheck(id) {
  proCheckStates[id] = !proCheckStates[id];
  document.getElementById('pro-item-' + id)
    .classList.toggle('checked', proCheckStates[id]);
}

